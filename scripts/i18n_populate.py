def compile_catalog(lang: str) -> None:
    """Write <lang>/LC_MESSAGES/messages.mo from the .po next to it."""
    base = os.path.join(ROOT, "translations", lang, "LC_MESSAGES", "messages")
    with open(base + ".po", "rb") as f:
        catalog = read_po(f, locale=lang)
    with open(base + ".mo", "wb") as f:
        write_mo(f, catalog)


def populate(lang: str, translations: dict[str, str]) -> None:
    po_path = os.path.join(ROOT, "translations", lang, "LC_MESSAGES", "messages.po")
    with open(po_path, "rb") as f:
        catalog = read_po(f)
    catalog.locale = lang
    filled = 0
    for message in catalog:
        if not message.id:
            continue
        if message.id in translations:
            message.string = translations[message.id]
            # pybabel update fuzzy-matches new entries; a canned translation
            # is authoritative, so drop the flag or i18n_status fails.
            message.flags.discard("fuzzy")
            filled += 1
    with open(po_path, "wb") as f:
        write_po(f, catalog)
    missing = [m.id for m in catalog if m.id and not m.string]
    print(f"{lang}: {filled} translations set, {len(missing)} still empty")
    if missing:
        print("  missing:")
        for mid in missing:
            print(f"    - {mid!r}")


def main() -> int:
    # English: msgstr = msgid for every message.
    en_path = os.path.join(ROOT, "translations", "en", "LC_MESSAGES", "messages.po")
    with open(en_path, "rb") as f:
        catalog_en = read_po(f)
    catalog_en.locale = "en"
    for message in catalog_en:
        # Unconditionally, not just for empty/fuzzy entries: pybabel update
        # fuzzy-matches new ids against old ones, and once that flag is lost
        # the wrong string sticks forever (this is how "Privacy" ended up
        # rendering as "Price" in the footer).
        if message.id:
            message.string = message.id
            message.flags.discard("fuzzy")
    with open(en_path, "wb") as f:
        write_po(f, catalog_en)
    print("en: mirrored source strings")

    for lang, translations in TRANSLATIONS.items():
        populate(lang, translations)

    # Runtime reads the .mo, never the .po: a catalog that isn't compiled
    # keeps serving the previous release's strings (or the bare English
    # msgids) no matter how complete i18n_status.py says it is.
    for lang in ("en", *TRANSLATIONS):
        compile_catalog(lang)
    print(f"compiled {len(TRANSLATIONS) + 1} catalogs to .mo")
    return 0


if __name__ == "__main__":
    sys.exit(main())
