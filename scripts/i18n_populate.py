def populate(lang: str, translations: dict[str, str]) -> None:
    po_path = os.path.join(ROOT, 'translations', lang, 'LC_MESSAGES', 'messages.po')
    with open(po_path, 'rb') as f:
        catalog = read_po(f)
    catalog.locale = lang
    filled = 0
    for message in catalog:
        if not message.id:
            continue
        if message.id in translations:
            message.string = translations[message.id]
            filled += 1
    with open(po_path, 'wb') as f:
        write_po(f, catalog)
    missing = [m.id for m in catalog if m.id and not m.string]
    print(f'{lang}: {filled} translations set, {len(missing)} still empty')
    if missing:
        print('  missing:')
        for mid in missing:
            print(f'    - {mid!r}')


def main() -> int:
    # English: msgstr = msgid for every message.
    en_path = os.path.join(ROOT, 'translations', 'en', 'LC_MESSAGES', 'messages.po')
    with open(en_path, 'rb') as f:
        catalog_en = read_po(f)
    catalog_en.locale = 'en'
    for message in catalog_en:
        if message.id and not message.string:
            message.string = message.id
    with open(en_path, 'wb') as f:
        write_po(f, catalog_en)
    print('en: mirrored source strings')

    for lang, translations in TRANSLATIONS.items():
        populate(lang, translations)
    return 0


